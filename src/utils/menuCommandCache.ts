import * as uxp from "uxp";
import { atomicWriteJSON, isNotFoundError } from "./atomicWriteJSON";
import type { FSFile } from "./uxpTypes";
import type { MenuCommandData } from "../commands/MenuCommand";

const { storage } = uxp;
const fs = storage.localFileSystem;

const CACHE_FILE_NAME = "menu-commands-cache.json";

// The cached `enabled`/`visible`/`checked` flags are a snapshot of whatever
// session wrote the cache, so they're stale until the live fetch replaces
// them. That's an accepted tradeoff, not an oversight: the palette neither
// filters nor styles rows on them (see renderCommandItem.ts), and
// launchPalette() re-fetches menu state in the background on every open.
type MenuCommandCacheFile = {
    hostVersion: string;
    generatedAt: string;
    commands: MenuCommandData[];
};

/**
 * Read the cached menu command list, if present and generated by the same
 * Photoshop version currently running. A version mismatch (or no cache at
 * all - first run) returns `null`, and menu commands simply aren't in the
 * store until the live `batchPlay` fetch resolves.
 */
export async function readMenuCommandCache(
    hostVersion: string
): Promise<MenuCommandData[] | null> {
    try {
        const dataFolder = await fs.getDataFolder();
        const file = (await dataFolder.getEntry(CACHE_FILE_NAME)) as FSFile;
        const raw = await file.read({ format: storage.formats.utf8 });
        const cache: MenuCommandCacheFile = JSON.parse(raw as string);

        if (cache.hostVersion !== hostVersion || !Array.isArray(cache.commands)) {
            return null;
        }
        return cache.commands;
    } catch (error) {
        // ENOENT/EntryNotFoundError (no cache file yet - first run, or it was
        // never successfully written) is the normal, expected case and not
        // worth logging. Anything else - corrupt JSON, a permission error,
        // some other unexpected read failure - still degrades to "no usable
        // cache" the same way, but is worth a debug trail instead of
        // silently looking identical to a routine first run.
        if (!isNotFoundError(error)) {
            console.warn("Failed to read menu command cache:", error);
        }
        return null;
    }
}

// Serializes cache writes, the same as `User`/`History`'s `writeChain`:
// atomicWriteJSON reuses fixed `.tmp`/`.bak` names, so two overlapping writes
// would race each other's renames. `writeNow()` never rejects, so the chain
// can't get stuck on a failed write.
let writeChain: Promise<void> = Promise.resolve();

/**
 * Persist a fresh menu command list to disk (fire-and-forget from the
 * caller's perspective - failures are logged, not thrown, since this is a
 * pure optimization and losing the cache just means next launch falls back
 * to a live-only fetch). Queued behind any write already in progress.
 */
export function writeMenuCommandCache(
    hostVersion: string,
    commands: MenuCommandData[]
): Promise<void> {
    writeChain = writeChain.then(() => writeNow(hostVersion, commands));
    return writeChain;
}

/** The actual cache write, queued by `writeMenuCommandCache()`. Logs failures, never throws. */
async function writeNow(
    hostVersion: string,
    commands: MenuCommandData[]
): Promise<void> {
    try {
        const dataFolder = await fs.getDataFolder();

        let existingFile: FSFile | null = null;
        try {
            existingFile = (await dataFolder.getEntry(CACHE_FILE_NAME)) as FSFile;
        } catch {
            existingFile = null;
        }

        const cache: MenuCommandCacheFile = {
            hostVersion,
            generatedAt: new Date().toISOString(),
            commands,
        };

        await atomicWriteJSON(dataFolder, CACHE_FILE_NAME, cache, existingFile);
    } catch (error) {
        console.error("Failed to write menu command cache:", error);
    }
}
